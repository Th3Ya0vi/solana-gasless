const { Keypair } = require('@solana/web3.js')
const fs = require('fs')
const path = require('path')

/**
 * Setup script to generate a fee payer keypair for gasless transactions
 * Run this once during initial setup
 */

function generateFeePayerKeypair() {
  console.log('🚀 Setting up Fee Payer Keypair for Gasless NFT Claims\n')
  
  const keypair = Keypair.generate()
  
  console.log('✅ Generated new fee payer keypair:')
  console.log('Public Key:', keypair.publicKey.toString())
  console.log('Private Key:', JSON.stringify(Array.from(keypair.secretKey)))
  console.log()
  
  // Save to file for development
  const keypairPath = path.join(__dirname, '..', 'fee-payer-keypair.json')
  const keypairData = {
    publicKey: keypair.publicKey.toString(),
    secretKey: Array.from(keypair.secretKey)
  }
  
  fs.writeFileSync(keypairPath, JSON.stringify(keypairData, null, 2))
  console.log(`💾 Keypair saved to: ${keypairPath}`)
  console.log('⚠️  Remember to add fee-payer-keypair.json to .gitignore!\n')
  
  // Create .env.local template
  const envPath = path.join(__dirname, '..', '.env.local')
  const envContent = `# Solana Gasless NFT Claiming Site Environment Variables
# Generated by setup script

# Fee Payer Private Key (keep this secret!)
FEE_PAYER_PRIVATE_KEY=${JSON.stringify(Array.from(keypair.secretKey))}

# Optional: Custom RPC endpoint
# SOLANA_RPC_URL=https://api.mainnet-beta.solana.com
`
  
  if (!fs.existsSync(envPath)) {
    fs.writeFileSync(envPath, envContent)
    console.log(`🔧 Created .env.local with your private key`)
  } else {
    console.log('⚠️  .env.local already exists, add the private key manually:')
    console.log(`FEE_PAYER_PRIVATE_KEY=${JSON.stringify(Array.from(keypair.secretKey))}`)
  }
  
  console.log('\n📋 Next Steps:')
  console.log('1. Fund your fee payer wallet with SOL (mainnet-beta for production):')
  console.log(`   # Note: You need to fund this wallet with real SOL on mainnet-beta`)
  console.log(`   # Public key: ${keypair.publicKey.toString()}`)
  console.log('2. Install dependencies:')
  console.log('   npm install')
  console.log('3. Start the development server:')
  console.log('   npm run dev')
  console.log('4. Visit http://localhost:3000 to test NFT claiming')
  console.log('\n🔐 Security Notes:')
  console.log('- Never commit your private key to version control')
  console.log('- Use a dedicated wallet for fee paying in production')
  console.log('- Monitor your fee payer balance regularly')
  console.log('- ⚠️  MAINNET WARNING: This wallet will need real SOL funding!')
  console.log('- Each NFT mint transaction will cost real SOL fees')
  console.log('\n🎉 Setup complete! Happy minting!')
}

generateFeePayerKeypair()
